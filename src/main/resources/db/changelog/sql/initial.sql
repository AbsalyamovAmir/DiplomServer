create table cwe
(
    id          bigint generated by default as identity,
    vul_id      bigint,
    identifier  varchar(20)  not null,
    description TEXT,
    name        varchar(255) not null,
    primary key (id)
);

create table operating_system
(
    id        bigint generated by default as identity,
    vendor_id bigint,
    vul_id    bigint,
    platform  varchar(100),
    version   varchar(100),
    name      varchar(255) not null,
    primary key (id)
);

create table software
(
    id              bigint generated by default as identity,
    softwaretype_id bigint,
    vendor_id       bigint,
    vul_id          bigint,
    platform        varchar(100),
    version         varchar(100),
    name            varchar(255) not null,
    primary key (id)
);

create table software_type
(
    id          bigint generated by default as identity,
    software_id bigint,
    name        varchar(100) not null,
    primary KEY (id)
);

create table source
(
    id     bigint generated by default as identity,
    vul_id bigint,
    url    varchar(500) not null,
    primary key (id)
);

create table vendor
(
    id   bigint generated by default as identity,
    name varchar(255) not null,
    primary key (id)
);

create table vulnerability
(
    cvss3_score    float(53),
    cvss_score     float(53),
    hash           integer,
    identify_date  date,
    vul_incident   boolean,
    cwe_id         bigint,
    id             bigint generated by default as identity,
    source_id      bigint,
    identifier     varchar(50)  not null unique,
    cvss3_vector   varchar(100),
    cvss_vector    varchar(100),
    exploit_status varchar(100),
    fix_status     varchar(100),
    vul_class      varchar(100),
    vul_state      varchar(100),
    vul_status     varchar(100),
    name           varchar(500) not null,
    description    TEXT,
    other          TEXT,
    severity       varchar(255),
    solution       TEXT,
    primary key (id)
);

create index idx_hash
    on vulnerability (hash);

